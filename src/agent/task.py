"""
Модуль для описания задач и их ограничений.

Этот модуль предоставляет класс :class:`Task` для описания задачи,
которую агент должен выполнить. Класс представляет собой неизменяемый
контейнер для параметров задачи и её ограничений.

Пример использования
--------------------

::

    from src.agent import Task
    
    # Создание задачи с лимитами
    task = Task(
        prompt="Посчитай факториал 17",
        max_steps=10,
        max_cost_usd=0.50
    )
    
    # Создание задачи с постусловием
    def verify_answer(answer: str) -> tuple[bool, str]:
        try:
            result = int(answer.strip())
            expected = 355687428096000  # 17!
            return result == expected, f"Результат: {result}"
        except ValueError:
            return False, "Ответ не является числом"
    
    task = Task(
        prompt="Посчитай 17 факториал",
        postcondition=verify_answer
    )

Смотрите также
--------------

:class:`Budget` — класс для управления ресурсами
:class:`Trace` — класс для трассировки выполнения
"""

import os
from dataclasses import dataclass
from typing import Callable

# --------------------------------------------------------------------------- #
# Задача
# --------------------------------------------------------------------------- #

@dataclass(frozen=True)
class Task:
    """
    Описание задачи и её ограничений для агента.
    
    Класс представляет собой неизменяемый (frozen=True) dataclass, который
    хранит инструкции для агента и определяет критерии успеха выполнения.
    Иммутабельность гарантирует, что агент не может изменить задачу в процессе
    выполнения, обеспечивая согласованность поведения.
    
    Архитектурные особенности
    --------------------------
    
    - **Иммутабельность**: объект Task неизменяем после создания (frozen=True)
    - **Атрибуты как параметры**: все атрибуты имеют значения по умолчанию
    - **Гибкая конфигурация**: лимиты можно задавать явно или через переменные окружения
    - **Постусловия**: опциональная проверка критериев успеха
    
    Атрибуты
    --------
    prompt : str
        Инструкция или запрос, который агент получает от пользователя.
        Определяет начальное состояние истории диалога.
    postcondition : Callable[[str], tuple[bool, str]] | None
        Функция для проверки выполнения задачи. Принимает текст ответа агента
        и возвращает кортеж (успешно: bool, сообщение: str).
        Если None, постусловие не проверяется.
    max_steps : int
        Максимальное количество шагов выполнения (вызовов LLM).
        По умолчанию берётся из переменной окружения AGENT_MAX_STEPS,
        если не задан явно. Значение по умолчанию: 16.
    max_seconds : float
        Максимальное время выполнения в секундах.
        По умолчанию берётся из переменной окружения AGENT_MAX_SECONDS.
        Значение по умолчанию: 300 (5 минут).
    max_tokens : int
        Максимальное количество токенов во входе и выходе.
        По умолчанию берётся из переменной окружения AGENT_MAX_TOKENS.
        Значение по умолчанию: 200_000.
    max_cost_usd : float
        Максимальная стоимость выполнения в долларах США.
        По умолчанию берётся из переменной окружения AAGENT_MAX_COST_USD.
        Значение по умолчанию: 0.50 USD.
    
    Примечания
    ----------
    
    - Класс является frozen (неизменяемым), поэтому атрибуты нельзя изменить
      после создания экземпляра
    - Все лимиты проверяются классом :class:`Budget` перед началом каждого шага
    - Постусловие проверяется после получения финального ответа агента
    
    Пример создания экземпляра
    ^^^^^^^^^^^^^^^^^^^^^^^^^^^
    
    .. code-block:: python
    
        from src.agent import Task
        
        # Минимальная задача
        task = Task(prompt="Посчитай 17!")
        
        # Задача с пользовательскими лимитами
        task = Task(
            prompt="Найди информацию о Python",
            max_steps=20,
            max_seconds=60.0,
            max_tokens=50000,
            max_cost_usd=0.25
        )
    
    Использование с постусловием
    ^^^^^^^^^^^^^^^^^^^^^^^^^^^^
    
    .. code-block:: python
    
        def is_factorial_correct(answer: str) -> tuple[bool, str]:
            \"\"\"Проверяет, что ответ содержит правильный результат факториала 17.\"\"\"
            try:
                result = int(answer.strip())
                expected = 355687428096000  # 17!
                if result == expected:
                    return True, "Результат верен"
                return False, f"Ожидалось {expected}, получено {result}"
            except ValueError:
                return False, "Ответ не является числом"
        
        task = Task(
            prompt="Посчитай 17 факториал",
            postcondition=is_factorial_correct
        )
    
    Смотрите также
    --------------
    
    :class:`Budget` — класс для управления ресурсами на основе лимитов задачи
    :class:`Trace` — класс для трассировки выполнения
    :func:`src.agent.task.verify` — функция для проверки постусловий
    """
    
    prompt: str
    postcondition: Callable[[str], tuple[bool, str]] | None = None
    max_steps: int = int(os.environ.get("AGENT_MAX_STEPS", 16))
    max_seconds: float = float(os.environ.get("AGENT_MAX_SECONDS", 300))
    max_tokens: int = int(os.environ.get("AGENT_MAX_TOKENS", 200_000))
    max_cost_usd: float = (os.environ.get("AAGENT_MAX_COST_USD", 0.50))